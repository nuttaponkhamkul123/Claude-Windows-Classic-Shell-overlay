  onSessionAlert: (callback) => ipcRenderer.on('session-alert', (_event, session) => callback(session)),
  onReplyStream: (callback) => ipcRenderer.on('reply-stream', (_event, data) => callback(data)),
  onReplyRekey: (callback) => ipcRenderer.on('reply-rekey', (_event, data) => callback(data)),
  onReplyStatus:(callback) => ipcRenderer.on('reply-status', (_event, data) => callback(data)),
  dismissSession: (sessionId) => ipcRenderer.send('dismiss-session', sessionId),
  sendReply: (payload) => ipcRenderer.send('send-reply', payload),
  // Real on-disk path of a picked / dropped file ('' for pasted data)
  rulesList: () => ipcRenderer.invoke('rules-list'),
  rulesDelete: (id) => ipcRenderer.invoke('rules-delete', id),
  rulesClear: () => ipcRenderer.invoke('rules-clear'),
  quickSnip: () => ipcRenderer.invoke('quick-snip'),
