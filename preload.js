  agyModels: () => ipcRenderer.invoke('agy-models'),
  openFolder: (dir) => ipcRenderer.invoke('open-folder', dir),
  pickFolder: (startDir) => ipcRenderer.invoke('pick-folder', startDir),
  folderExists: (dir) => ipcRenderer.invoke('folder-exists', dir),
  // Extra features (features-main.js)
  storeGetAll: () => ipcRenderer.invoke('store-get-all'),
  storeSet: (key, value) => ipcRenderer.send('store-set', { key, value }),
  searchTranscripts: (q) => ipcRenderer.invoke('search-transcripts', q),
  openFile: (p) => ipcRenderer.invoke('open-file', p),
  stopReply: (sessionId) => ipcRenderer.invoke('stop-reply', sessionId),
  voiceTyping: () => ipcRenderer.invoke('voice-typing'),
  getDigest: () => ipcRenderer.invoke('get-digest'),
  getSessionCosts: (ids) => ipcRenderer.invoke('get-session-costs', ids),
